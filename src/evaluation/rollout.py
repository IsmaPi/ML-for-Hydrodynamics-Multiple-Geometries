"""Autoregressive rollout evaluation for multi-step prediction accuracy.

A "rollout" is an autoregressive simulation: starting from an initial
configuration, the model predicts the displacement at each step, the
predicted displacement is applied to update positions, and the updated
positions are fed back as input for the next step.  This evaluates how
prediction errors accumulate over many steps.

Iterates Q^{n+1} = Q^n + DeltaX_hat^n and compares the resulting
position sequence against ground-truth generated by libMobility (or
a synthetic Oseen-tensor approximation).
"""

import torch
import numpy as np
from typing import Optional
from torch_geometric.data import Data

from ..data.geometry import build_geometry_params, get_geometry_constraints
from ..data.dataset import make_box_vecs
from ..data.generate import (
    sample_forces, enforce_boundaries,
    generate_trajectory,
)
from ..data.normalization import FeatureNormalizer

TORCHMD_MODELS = {"torchmd_gn", "torchmd_et"}


@torch.no_grad()
def evaluate_rollout(
    model: torch.nn.Module,
    geometry_key: str,
    config: dict,
    normalizer: Optional[FeatureNormalizer],
    N: int,
    num_steps: int,
    dt: float,
    device: torch.device,
    model_type: str = "torchmd_gn",
    cutoff_radius: float = 30.0,
    use_synthetic: bool = True,
    seed: int = 123,
) -> dict:
    """Run autoregressive rollout and compare to ground truth.

    The model predicts single-step displacements from (positions, forces, theta).
    Stokes flow is memoryless: each prediction depends only on the current state,
    not on any history.

    Returns:
        pred_positions: (num_steps+1, N, 3) predicted position sequence
        true_positions: (num_steps+1, N, 3) ground-truth position sequence
        per_step_error: (num_steps,) RMSE per step
        cumulative_error: (num_steps,) cumulative RMSE
    """
    model.eval()
    rng = np.random.default_rng(seed)
    force_scale = config.get("force_scale", 1.0)

    # Generate ground truth trajectory
    true_traj = generate_trajectory(
        geometry_key=geometry_key,
        config=config,
        N=N,
        T_steps=num_steps,
        dt=dt,
        force_scale=force_scale,
        rng=np.random.default_rng(seed),  # same seed for same initial conditions
        use_synthetic=use_synthetic,
    )

    theta = build_geometry_params(geometry_key, config).to(device)
    theta_expanded = theta.unsqueeze(0).expand(N, -1)

    # Precompute box_vecs for periodic geometries
    box_vecs = make_box_vecs(geometry_key, theta)
    if box_vecs is not None:
        box_vecs = box_vecs.to(device)

    # Model rollout using the SAME initial conditions and forces
    pred_positions = np.zeros((num_steps + 1, N, 3))
    pred_positions[0] = true_traj["positions"][0]

    for n in range(num_steps):
        pos_np = pred_positions[n]
        forces_np = true_traj["forces"][n]  # same forces as ground truth

        pos_t = torch.tensor(pos_np, dtype=torch.float32, device=device)
        forces_t = torch.tensor(forces_np, dtype=torch.float32, device=device)

        if normalizer:
            forces_norm = normalizer.transform(forces_t.cpu(), "forces").to(device)
        else:
            forces_norm = forces_t

        # Node features: [forces(3), theta(6)]
        node_features = torch.cat([forces_norm, theta_expanded], dim=-1)

        data = Data(
            x=node_features,
            pos=pos_t,
            box_vecs=box_vecs,
        )
        data.batch = torch.zeros(N, dtype=torch.long, device=device)

        pred_disp = model(data)

        if normalizer:
            pred_disp = normalizer.inverse_transform(pred_disp.cpu(), "displacements").numpy()
        else:
            pred_disp = pred_disp.cpu().numpy()

        pred_positions[n + 1] = pred_positions[n] + pred_disp
        pred_positions[n + 1] = enforce_boundaries(pred_positions[n + 1], geometry_key, config)

    true_positions = true_traj["positions"]

    # Per-step RMSE
    per_step_error = np.sqrt(
        ((pred_positions[1:] - true_positions[1:]) ** 2).sum(axis=-1).mean(axis=-1)
    )
    cumulative_error = np.cumsum(per_step_error)

    return {
        "pred_positions": pred_positions,
        "true_positions": true_positions,
        "per_step_error": per_step_error,
        "cumulative_error": cumulative_error,
    }
